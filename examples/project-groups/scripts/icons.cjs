#!/usr/bin/env node
"use strict";

// Rewrites the icon block in ../renderer.js with lucide icon data taken from T3 Code's own bundle,
// so the group icon picker offers exactly the icons T3's project icon picker offers.
//
//   ELECTRON_RUN_AS_NODE=1 "/Applications/T3 Code (Nightly).app/Contents/MacOS/T3 Code (Nightly)" scripts/icons.cjs
//   node scripts/icons.cjs <directory with T3's client assets>
//
// Plain Node cannot read inside app.asar; T3's binary running as Node can.

const fs = require("node:fs");
const path = require("node:path");

const DEFAULT_ASSETS = "/Applications/T3 Code (Nightly).app/Contents/Resources/app.asar/apps/server/dist/client/assets";
const RENDERER = path.join(__dirname, "..", "renderer.js");
const BEGIN = "// <icons>";
const END = "// </icons>";

// T3's project icon picker list, in its order, then the icons this extension's own UI uses.
const PICKER = ["folder-code", "code-2", "terminal", "globe-2", "server", "database", "bot", "sparkles", "smartphone", "monitor", "cloud-cog", "package", "book-open", "flask-conical", "shield-check", "rocket", "gamepad-2", "music", "image", "shopping-bag", "git-branch", "workflow", "wrench", "layers-3"];
const UI = ["list-filter", "folder", "plus", "pencil", "check", "search"];

const pascal = (name) => name.split("-").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");
const kebab = (name) => (name.match(/[A-Z][a-z]*|[0-9]+[a-z]*/g) ?? []).join("-").toLowerCase();

// The text from `start` up to the bracket that closes the one at `start`, skipping template strings.
function balanced(source, start) {
  let depth = 0;
  for (let i = start; i < source.length; i++) {
    const c = source[i];
    if (c === "`") i = source.indexOf("`", i + 1);
    else if (c === "[") depth++;
    else if (c === "]" && --depth === 0) return source.slice(start, i + 1);
  }
  return null;
}

// `[[`path`,{d:`M2 5h20`,key:`x`}]]` is a JS literal, not JSON. Parse it without evaluating it.
function parseNodes(literal) {
  const json = literal.replace(/`([^`]*)`/g, (_, text) => JSON.stringify(text)).replace(/([{,])([A-Za-z][\w-]*):/g, '$1"$2":');
  return JSON.parse(json).map(([tag, attrs]) => {
    const { key, ...rest } = attrs;
    return [tag, rest];
  });
}

function readIcons(dir) {
  const definitions = new Map();
  const exportMaps = [];
  for (const file of fs.readdirSync(dir).filter((name) => name.endsWith(".js"))) {
    const source = fs.readFileSync(path.join(dir, file), "utf8");
    for (const match of source.matchAll(/[\w$]+\(`([a-z0-9-]+)`,(?=\[\[`[a-z]+`,\{)/g)) {
      if (definitions.has(match[1])) continue;
      const literal = balanced(source, match.index + match[0].length);
      if (literal) definitions.set(match[1], parseNodes(literal));
    }
    // lucide's `icons` export map, `Layers3:()=>Ab,Layers:()=>Ab`, tells which names are aliases.
    const exported = new Map([...source.matchAll(/([A-Z][A-Za-z0-9]*):\(\)=>([\w$]+)/g)].map((match) => [match[1], match[2]]));
    if (exported.size) exportMaps.push(exported);
  }
  const resolve = (name) => {
    if (definitions.has(name)) return definitions.get(name);
    for (const exported of exportMaps.filter((map) => map.has(pascal(name)))) {
      for (const [other, binding] of exported) {
        if (binding === exported.get(pascal(name)) && definitions.has(kebab(other))) return definitions.get(kebab(other));
      }
    }
    throw new Error(`no lucide icon "${name}" in ${dir}`);
  };
  return Object.fromEntries([...PICKER, ...UI].map((name) => [name, resolve(name)]));
}

function main() {
  const dir = process.argv[2] ?? DEFAULT_ASSETS;
  const icons = readIcons(dir);
  const lines = Object.entries(icons).map(([name, nodes]) => `    ${JSON.stringify(name)}: ${JSON.stringify(nodes)},`);
  const block = [
    BEGIN,
    "  // Generated by scripts/icons.cjs from the lucide icons in T3 Code's bundle. Lucide is ISC licensed.",
    `  const PICKER_ICONS = ${JSON.stringify(PICKER)};`,
    "  const ICONS = {",
    ...lines,
    "  };",
    `  ${END}`,
  ].join("\n");
  const renderer = fs.readFileSync(RENDERER, "utf8");
  const begin = renderer.indexOf(BEGIN);
  const end = renderer.indexOf(END);
  if (begin < 0 || end < begin) throw new Error(`${RENDERER} has no ${BEGIN} ... ${END} block`);
  fs.writeFileSync(RENDERER, renderer.slice(0, begin) + block + renderer.slice(end + END.length));
  console.log(`wrote ${Object.keys(icons).length} icons into ${RENDERER}`);
}

main();
