"use strict";

// Builds "T3 Code+.app": a tiny ad-hoc-signed app outside T3's bundle that runs `t3ext launch`.

const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { plistValue } = require("./launcher.cjs");
const { pickNodeShell } = require("./pick-node.cjs");

const NAME = "T3 Code+";
const BUNDLE_ID = "dev.t3ext.launcher";
const EXECUTABLE = "t3code-plus";

function shellQuote(value) {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function script({ app, cliPath, fallbackNode }) {
  return `#!/bin/sh
# Generated by "t3ext install-launcher". T3EXT_APP overrides the target app;
# T3EXT_LAUNCH_ARGS adds arguments to "t3ext launch" (split on spaces).
DEFAULT_APP=${shellQuote(app)}
APP="\${T3EXT_APP:-$DEFAULT_APP}"
CLI=${shellQuote(cliPath)}
FALLBACK_NODE=${shellQuote(fallbackNode)}
LOG="$HOME/Library/Logs/t3ext.log"
mkdir -p "$(dirname "$LOG")"
${pickNodeShell()}

if [ -n "$NODE" ]; then
  ELECTRON_RUN_AS_NODE=1 "$NODE" "$CLI" launch --app "$APP" $T3EXT_LAUNCH_ARGS >>"$LOG" 2>&1
else
  echo "$(date) $APP cannot run as node; using $FALLBACK_NODE" >>"$LOG"
  "$FALLBACK_NODE" "$CLI" launch --app "$APP" $T3EXT_LAUNCH_ARGS >>"$LOG" 2>&1
fi
STATUS=$?
if [ "$STATUS" -ne 0 ]; then
  /usr/bin/osascript -e 'display notification "Extensions were not loaded. See ~/Library/Logs/t3ext.log" with title "T3 Code+"' >/dev/null 2>&1
fi
exit "$STATUS"
`;
}

function infoPlist({ version }) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key>
  <string>${NAME}</string>
  <key>CFBundleDisplayName</key>
  <string>${NAME}</string>
  <key>CFBundleIdentifier</key>
  <string>${BUNDLE_ID}</string>
  <key>CFBundleExecutable</key>
  <string>${EXECUTABLE}</string>
  <key>CFBundleIconFile</key>
  <string>icon.icns</string>
  <key>CFBundlePackageType</key>
  <string>APPL</string>
  <key>CFBundleShortVersionString</key>
  <string>${version}</string>
  <key>LSUIElement</key>
  <true/>
</dict>
</plist>
`;
}

// Everything install-launcher writes, so --dry-run can print exactly that.
function plan({ app, destDir = path.join(os.homedir(), "Applications"), cliPath, fallbackNode = process.execPath, version }) {
  const bundle = path.join(destDir, `${NAME}.app`);
  const icon = path.join(app, "Contents", "Resources", plistValue(app, "CFBundleIconFile").replace(/(\.icns)?$/, ".icns"));
  return {
    bundle,
    files: [
      { path: path.join(bundle, "Contents", "Info.plist"), content: infoPlist({ version }) },
      { path: path.join(bundle, "Contents", "MacOS", EXECUTABLE), content: script({ app, cliPath, fallbackNode }), mode: 0o755 },
      { path: path.join(bundle, "Contents", "Resources", "icon.icns"), copyFrom: icon },
    ],
  };
}

function build(planned) {
  const tmp = path.join(path.dirname(planned.bundle), `.t3ext-tmp-${path.basename(planned.bundle)}`);
  fs.rmSync(tmp, { recursive: true, force: true });
  for (const file of planned.files) {
    const target = path.join(tmp, path.relative(planned.bundle, file.path));
    fs.mkdirSync(path.dirname(target), { recursive: true });
    if (file.copyFrom) fs.copyFileSync(file.copyFrom, target);
    else fs.writeFileSync(target, file.content, { mode: file.mode ?? 0o644 });
  }
  execFileSync("codesign", ["--force", "--sign", "-", tmp], { stdio: "ignore" });
  fs.rmSync(planned.bundle, { recursive: true, force: true });
  fs.renameSync(tmp, planned.bundle);
  return planned.bundle;
}

module.exports = { plan, build, NAME, BUNDLE_ID };
